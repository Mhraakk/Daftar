/** استخراج فیلدهای پویا از متن قالب */
export function extractFields(html: string): string[] {
  return [...new Set([...html.matchAll(/\{\{\s*([^{}]+?)\s*\}\}/g)].map((m) => m[1].trim()))];
}

export async function seedTemplates(db: PrismaClient) {
  for (const t of TEMPLATES) {
    const exists = await db.legalTemplate.findFirst({ where: { name: t.name, isSystem: true } });
    if (exists) continue;
    await db.legalTemplate.create({
      data: {
        name: t.name, docType: t.docType, category: t.category, description: t.description, legalBasis: t.legalBasis, isSystem: true,
        versions: { create: { versionNo: 1, contentHtml: t.html.trim(), fields: extractFields(t.html), note: "نسخه پایه سامانه" } },
      },
    });
  }
}
